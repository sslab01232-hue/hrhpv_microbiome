# Network functions used for the resampling analyses in 04_network.R.
# SparCC, network construction, and network properties follow SpiecEasi and
# NetCoMi 1.3.0 (signed dissimilarity, centrLCC = TRUE, fast-greedy clustering).

# SparCC (SpiecEasi::sparcc) --------------------------------------------------
clr_vec <- function(x, tol = .Machine$double.eps) {
  nz <- x >= tol
  l <- log(ifelse(nz, x, 1))
  ifelse(nz, l - mean(l) / mean(nz), 0)
}

variation_mat <- function(x) {
  cv <- cov(apply(x, 2, clr_vec))
  outer(diag(cv), diag(cv), "+") - 2 * cv
}

basis_var <- function(Tm, M, excluded = NULL, vmin = 1e-4) {
  if (!is.null(excluded)) Tm[excluded] <- 0
  Mi <- tryCatch(solve(M), error = function(e) MASS::ginv(M))
  v <- Mi %*% rowSums(Tm)
  v[v < vmin] <- vmin
  v
}

cor_from_var <- function(Tm, v) {
  cv <- 0.5 * (outer(c(v), c(v), "+") - Tm)
  r <- cov2cor((cv + t(cv)) / 2)
  r[abs(r) > 1] <- sign(r[abs(r) > 1])
  r
}

sparcc_inner <- function(frac, iter = 20, th = 0.1) {
  Tm <- variation_mat(frac)
  p  <- ncol(Tm)
  M  <- matrix(1, p, p) + diag(p) * (p - 2)
  r  <- cor_from_var(Tm, basis_var(Tm, M))
  excluded <- NULL
  for (k in seq_len(iter)) {                     # iterative exclusion of strongly correlated pairs
    ct <- abs(r - diag(diag(r)))
    if (!is.null(excluded)) ct[excluded] <- 0
    if (max(ct) <= th) break
    ex <- which(abs(ct - max(ct)) < .Machine$double.eps * 100)[1:2]
    i  <- na.exclude(arrayInd(ex, dim(M))[, 1])
    M[i, i] <- M[i, i] - 1
    excluded <- c(excluded, ex)
    r <- cor_from_var(Tm, basis_var(Tm, M, excluded))
  }
  r
}

sparcc <- function(counts, iter = 100, inner_iter = 20, th = 0.1) {
  cors <- replicate(iter, {
    frac <- t(apply(counts, 1, function(x) { d <- VGAM::rdiric(1, x + 1); colMeans(d) / sum(colMeans(d)) }))
    sparcc_inner(frac, inner_iter, th)
  })
  r <- apply(cors, 1:2, median)
  dimnames(r) <- list(colnames(counts), colnames(counts))
  r
}

# Network construction and properties (NetCoMi netConstruct / netAnalyze) ------
is_edge <- function(r, th) abs(r) >= th & r > -1    # r = -1 has similarity 0 (signed)

build_net <- function(r, th) {
  a <- r
  a[abs(a) < th] <- 0
  d <- sqrt(0.5 * (1 - a))
  d[a == 0] <- Inf
  diag(d) <- 0
  s <- 1 - d
  s[is.infinite(d)] <- 0
  list(asso = a, diss = d, adja = s)
}

natural_connectivity <- function(A) {
  ev <- eigen(A)$values
  n  <- length(ev)
  log(mean(exp(ev))) / (n - log(n))
}

calc_props <- function(nw) {
  A <- nw$adja; D <- nw$diss; nm <- colnames(A); zero <- setNames(numeric(length(nm)), nm)
  if (all(A[lower.tri(A)] == 0))
    return(list(clustCoef = 0, modularity = 0, pep = 0, density = 0, natConnect = 0, nEdges = 0,
                deg = zero, betw = zero, close = zero, eigen = zero))
  g    <- graph_from_adjacency_matrix(A, weighted = TRUE, mode = "undirected", diag = FALSE)
  comp <- decompose(g)
  lcc  <- comp[[which.max(sapply(comp, vcount))]]
  ln   <- V(lcc)$name
  Dl   <- D[ln, ln]
  Dl0  <- replace(Dl, is.infinite(Dl), 0)
  gd   <- graph_from_adjacency_matrix(Dl0, weighted = TRUE, mode = "undirected", diag = FALSE)
  cl   <- cluster_fast_greedy(g)
  memb <- setNames(cl$membership, cl$names)
  memb[memb %in% which(table(memb) == 1)] <- 0
  dv   <- Dl[lower.tri(Dl)]; dv[is.infinite(dv)] <- 1
  sp   <- distances(gd, algorithm = "dijkstra") / mean(dv)
  lt   <- nw$asso[lower.tri(nw$asso)]
  cc   <- mean(transitivity(g, type = "barrat"), na.rm = TRUE)

  deg  <- degree(g, normalized = TRUE); deg[!names(deg) %in% ln] <- 0
  betw <- zero; b <- betweenness(gd, normalized = TRUE); betw[names(b)] <- replace(b, is.nan(b), 0)
  clo  <- zero; inv <- 1 / sp; diag(inv) <- NA; clo[ln] <- rowSums(inv, na.rm = TRUE) / (length(ln) - 1)
  eig  <- zero; ev <- eigen_centrality(lcc)$vector; eig[names(ev)] <- ev

  list(clustCoef  = if (is.nan(cc)) 0 else cc,
       modularity = modularity(g, memb + 1, weights = E(g)$weight),
       pep        = 100 * sum(lt > 0) / sum(lt != 0),
       density    = edge_density(g),
       natConnect = natural_connectivity(A),
       nEdges     = sum(A[lower.tri(A)] != 0),
       deg = deg[nm], betw = betw[nm], close = clo[nm], eigen = eig[nm])
}


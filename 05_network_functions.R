CENT <- c(deg = "Degree", betw = "Betweenness", close = "Closeness", eigen = "Eigenvector")

# Group-label permutations as generated by NetCoMi::netCompare ---------------
perm_group_mat <- function(n1, n2, n_perm) {
  g <- rep(1:2, c(n1, n2))
  clean <- function(m) { m <- unique.matrix(m); m[!apply(m, 1, identical, g), , drop = FALSE] }
  m <- clean(t(replicate(n_perm + 10, sample(g))))
  while (nrow(m) < n_perm) m <- clean(rbind(m, sample(g)))
  m[seq_len(n_perm), ]
}
